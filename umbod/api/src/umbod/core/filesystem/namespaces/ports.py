from typing import Protocol
from uuid import UUID

from ..models import Principal
from .models import CreateSharedNamespace, NamespaceDetails, NamespacePolicy, SaveSharedNamespace, SaveSharedNamespaceDescription, SharedNamespaceView


class NamespaceRegistry(Protocol):
    async def provision_personal(self, user: Principal) -> NamespacePolicy: ...
    async def list(self) -> list[NamespaceDetails]: ...
    async def create(self, command: CreateSharedNamespace, issuer: str) -> SharedNamespaceView: ...
    async def save(self, namespace_id: UUID, command: SaveSharedNamespace | SaveSharedNamespaceDescription, issuer: str) -> SharedNamespaceView: ...


class NamespaceManagement(Protocol):
    async def list(self) -> list[SharedNamespaceView]: ...
    async def create(self, command: CreateSharedNamespace) -> SharedNamespaceView: ...
    async def save(self, namespace_id: UUID, command: SaveSharedNamespace | SaveSharedNamespaceDescription) -> SharedNamespaceView: ...
